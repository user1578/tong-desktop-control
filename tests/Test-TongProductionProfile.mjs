assert.equal((await api.readApprovedEnabledState(enabled)).agentdockEnabled,true);
await assert.rejects(api.readApprovedEnabledState({...enabled,releaseDigest:'d'.repeat(64)}), /APPROVAL_DENIED/);
// A hardlinked bootstrap index must not overwrite another protected PoC file on renewal.
const hardlinkTarget=join(sim.root,'bootstrap-hardlink.txt');
