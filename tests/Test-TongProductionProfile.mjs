const enabled = api.createProductionSimulationProfile({simulationId,sourceDigest,releaseDigest,agentdockEnabled:true});
await assert.rejects(api.recordApprovedEnabledState(enabled), /APPROVAL_DENIED/);
await api.issueSimulationApproval(enabled,'enable-agentdock');
