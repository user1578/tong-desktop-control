assert.ok(api, 'production profile implementation is required');
const sourceDigest = 'a'.repeat(64), releaseDigest = 'b'.repeat(64);
const fixed = api.createProductionProfile({ sourceDigest, releaseDigest });
assert.equal(fixed.root, 'D:\\Tong\\runtime');
assert.equal(fixed.managerRoot, 'D:\\Tong\\runtime\\releases\\manager');
assert.equal(fixed.codeRoot, 'D:\\Tong\\app');
assert.equal(fixed.runtimeDir, 'D:\\Tong\\app\\runtime');
assert.equal(fixed.configDir, 'C:\\Users\\Rune\\.devspace');
assert.equal(fixed.oauthStateDir, 'C:\\Users\\Rune\\.local\\share\\devspace');
assert.equal(fixed.publicOrigin, 'https://retold-pointer-irregular.ngrok-free.dev');
assert.equal(fixed.agentdockEnabled, false);
assert.ok(Object.isFrozen(fixed));
for (const changed of [{root:'D:\\elsewhere'}, {managerRoot:'D:\\elsewhere'}, {codeRoot:'D:\\tong-agentdock-local\\releases\\candidate'}, {gatewayPort:17876}, {agentdockEnabled:1}, {extra:true}, {releaseDigest:''}]) {
  assert.throws(() => api.validateProductionProfile({...fixed,...changed}), /PROFILE_DENIED/);
}
assert.throws(() => api.createProductionProfile({sourceDigest,releaseDigest,root:'D:\\elsewhere'}), /PROFILE_DENIED/);
const simulationId = 'b23-profile-' + randomBytes(7).toString('hex');
const sim = api.createProductionSimulationProfile({simulationId,sourceDigest,releaseDigest});
assert.equal(sim.mode, 'production-simulation');
assert.ok(sim.root.startsWith('D:\\Tong\\state\\'));
assert.ok(sim.codeRoot.startsWith(sim.root+'\\'));
assert.equal(sim.managerRoot,sim.root+'\\releases\\manager');
assert.ok(sim.originalStateRoot.startsWith(sim.root+'\\'));
assert.notEqual(api.productionProfileDigest(sim), api.productionProfileDigest(fixed));
assert.throws(() => api.createProductionSimulationProfile({simulationId:'..',sourceDigest,releaseDigest}), /PROFILE_DENIED/);
assert.throws(() => api.validateProductionProfile({...sim,configDir:fixed.configDir}), /PROFILE_DENIED/);
await assert.rejects(api.issueSimulationApproval(fixed,'init'), /SIMULATION_ONLY/);
// No receipt, forged CLI flags and changed settings are all fail-closed.
await assert.rejects(api.verifyRuntimeApproval(sim,'init'), /APPROVAL_DENIED/);
await assert.rejects(api.initializeProductionRoot(sim,{approved:true}), /APPROVAL_DENIED/);
await assert.rejects(lstat(sim.root), {code:'ENOENT'});
process.env.TONG_PRODUCTION_APPROVED = '1';
await assert.rejects(api.verifyRuntimeApproval(sim,'start'), /APPROVAL_DENIED/);
delete process.env.TONG_PRODUCTION_APPROVED;
const receipt = await api.issueSimulationApproval(sim,'init');
assert.equal((await api.verifyRuntimeApproval(sim,'init')).action, 'init');
assert.deepEqual(await api.loadApprovedProfile(sim.root,'init'),sim);
await api.issueSimulationApproval(sim,'init');
assert.equal((await api.verifyRuntimeApproval(sim,'init')).action,'init','same reviewed profile/action can be renewed after a new approval');
await assert.rejects(api.loadApprovedProfile('D:\\elsewhere','init'), /PROFILE_DENIED/);
await assert.rejects(api.getApprovedProductionProfile('restore'), /APPROVAL_DENIED/);
await api.issueSimulationApproval(sim,'manager');
assert.deepEqual(await api.loadApprovedProfile(sim.root,'manager'),sim);
assert.equal((await api.verifyRuntimeApproval(sim,'manager')).action,'manager');
const sealed = await readFile(receipt.path);
assert.ok(!sealed.includes(Buffer.from('"profileDigest"')), 'receipt plaintext is DPAPI sealed');
await assert.rejects(api.verifyRuntimeApproval(sim,'start'), /APPROVAL_DENIED/);
await assert.rejects(api.verifyRuntimeApproval({...sim,agentdockEnabled:true},'init'), /APPROVAL_DENIED/);
await assert.rejects(api.verifyRuntimeApproval({...sim,releaseDigest:'c'.repeat(64)},'init'), /APPROVAL_DENIED/);
const damaged = JSON.parse(sealed); const bytes=Buffer.from(damaged.ciphertext,'base64'); bytes[bytes.length-10]^=1; damaged.ciphertext=bytes.toString('base64');
await writeFile(receipt.path,JSON.stringify(damaged));
await assert.rejects(api.verifyRuntimeApproval(sim,'init'), /APPROVAL_DENIED/);
await assert.rejects(api.initializeProductionRoot(sim), /APPROVAL_DENIED/);
await assert.rejects(lstat(sim.root), {code:'ENOENT'});
await writeFile(receipt.path,sealed);
const initialized = await api.initializeProductionRoot(sim);
assert.equal(initialized.root,sim.root);
assert.equal(initialized.created,true);
assert.equal((await api.initializeProductionRoot(sim)).created,false,'known protected root may be reopened without resetting state');
