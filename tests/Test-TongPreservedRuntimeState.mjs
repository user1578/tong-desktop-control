import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile,readFile} from 'node:fs/promises';
import {join} from 'node:path';
import * as z from 'zod/v4';
import {configureTongMcpState,registerTongMcpTools,closeTongMcpTools} from '../scripts/TongMcpTools.mjs';
const root=await mkdtemp('D:\\agentdock-poc-20261010\\isolated\\state\\b23-preserved-');
const stateDir=join(root,'original-runtime'),demoRoot=join(root,'original-demo');
await mkdir(stateDir);await mkdir(demoRoot);
await writeFile(join(stateDir,'project-access.json'),JSON.stringify({schemaVersion:1,projects:[]}));
await writeFile(join(stateDir,'agent-execution.json'),JSON.stringify({schemaVersion:1,projects:[]}));
await writeFile(join(stateDir,'trusted-codex.json'),JSON.stringify({schemaVersion:1,enabled:false,generation:4,projects:[],approvals:[]}));
await writeFile(join(stateDir,'trusted-codex.json.stop'),'synthetic stopped');
const before=await readFile(join(stateDir,'trusted-codex.json'));
process.env.TONG_RESTRICTED_MCP='1';delete process.env.TONG_LOCAL_STATE_DIR;delete process.env.TONG_AGENTDOCK_ENABLED;
assert.throws(()=>configureTongMcpState({stateDir:'relative',demoRoot}),/absolute/);
configureTongMcpState({stateDir,demoRoot,scanRoots:[]});
const tools=new Map();registerTongMcpTools({},(_server,name,definition,handler)=>tools.set(name,{definition,handler}),z);
assert.ok(tools.has('tong_agent_start')&&tools.has('tong_agent_list'));
assert.ok(!tools.has('tong_agentdock_file_edit'));
const result=await tools.get('tong_list_projects').handler({});
assert.equal(result.structuredContent.projects.find(p=>p.id==='demo').root,demoRoot);
assert.deepEqual(await readFile(join(stateDir,'trusted-codex.json')),before);
assert.equal(await readFile(join(stateDir,'trusted-codex.json.stop'),'utf8'),'synthetic stopped');
await closeTongMcpTools();
console.log(JSON.stringify({passed:true,root,originalStateSelected:true,codexToolsPreserved:true,newToolsOff:true,trustedStopUnchanged:true}));
